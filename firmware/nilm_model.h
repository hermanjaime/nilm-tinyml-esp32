/* ── Comparator for qsort (percentiles) ────────────────────── */
static int nilm_cmpf(const void *a, const void *b) {
    float fa=*(const float*)a, fb=*(const float*)b;
    return (fa>fb)-(fa<fb);
}

/* ── Extraction of the 9 features ──────────────────────────── */
static inline void nilm_extract_s3(const float w[NILM_WINDOW_SIZE],
                                    float out[NILM_N_FEATURES]) {
    int i;
    float sum=0.0f, ssq=0.0f, mn=w[0], mx=w[0];
    for(i=0;i<NILM_WINDOW_SIZE;i++) {
        sum+=w[i]; ssq+=w[i]*w[i];
        if(w[i]<mn) mn=w[i];
        if(w[i]>mx) mx=w[i];
    }
    float mean=sum/(float)NILM_WINDOW_SIZE, var=0.0f;
    for(i=0;i<NILM_WINDOW_SIZE;i++) { float d=w[i]-mean; var+=d*d; }
    float std_v=sqrtf(var/(float)NILM_WINDOW_SIZE);

    float sorted[NILM_WINDOW_SIZE];
    memcpy(sorted, w, sizeof(float)*NILM_WINDOW_SIZE);
    qsort(sorted, NILM_WINDOW_SIZE, sizeof(float), nilm_cmpf);

    out[0]=mean;           /* mean         */
    out[1]=std_v;          /* std          */
    out[2]=std_v;          /* rms_ac == std (mean already removed) */
    out[3]=mn;             /* min          */
    out[4]=mx;             /* max          */
    out[5]=mx-mn;          /* peak_to_peak */
    out[6]=ssq;            /* energy       */
    out[7]=sorted[(int)(0.05f*(NILM_WINDOW_SIZE-1))];  /* p05 */
    out[8]=sorted[(int)(0.95f*(NILM_WINDOW_SIZE-1))];  /* p95 */
}

/* ── Normalization (StandardScaler) ────────────────────────── */
static inline void nilm_normalize_s3(const float raw[NILM_N_FEATURES],
                                      float out[NILM_N_FEATURES]) {
    for(int i=0;i<NILM_N_FEATURES;i++)
        out[i]=(raw[i]-NILM_SCALER_MEAN[i])/NILM_SCALER_STD[i];
}

/* ── Forward Pass MLP ──────────────────────────────────────── */
static inline void nilm_predict_s3(const float sc[NILM_N_FEATURES],
                                    float out[NILM_N_OUTPUTS]) {
    float a0[32], a1[16], a2[8]; int i,j;
    for(j=0;j<32;j++) { float z=NILM_B0[j];
        for(i=0;i<9; i++) z+=sc[i]*NILM_W0[i][j]; a0[j]=z>0?z:0; }
    for(j=0;j<16;j++) { float z=NILM_B1[j];
        for(i=0;i<32;i++) z+=a0[i]*NILM_W1[i][j]; a1[j]=z>0?z:0; }
    for(j=0;j<8; j++) { float z=NILM_B2[j];
        for(i=0;i<16;i++) z+=a1[i]*NILM_W2[i][j]; a2[j]=z>0?z:0; }
    for(j=0;j<3; j++) { float z=NILM_B3[j];
        for(i=0;i<8; i++) z+=a2[i]*NILM_W3[i][j];
        out[j]=1.0f/(1.0f+expf(-z)); }
}

/* ── Classification ────────────────────────────────────────── */
static inline void nilm_classify_s3(const float out[NILM_N_OUTPUTS],
                                     uint8_t lbl[NILM_N_OUTPUTS],
                                     float threshold) {
    for(int j=0;j<NILM_N_OUTPUTS;j++)
        lbl[j]=(out[j]>=threshold)?1:0;
}

/* ── Complete pipeline (main entry function) ───────────────── */
static inline void nilm_run_s3(const float window[NILM_WINDOW_SIZE],
                                 float probs[NILM_N_OUTPUTS],
                                 uint8_t labels[NILM_N_OUTPUTS]) {
    float raw[NILM_N_FEATURES], sc[NILM_N_FEATURES];
    nilm_extract_s3(window, raw);
    nilm_normalize_s3(raw, sc);
    nilm_predict_s3(sc, probs);
    nilm_classify_s3(probs, labels, NILM_THRESHOLD);
}

